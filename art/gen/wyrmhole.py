"""ui_wyrmhole: the wyrmhole cell on the mine screen (and its buttons): a purple vortex, two light spiral arms that turn around a dark core.
Same footprint as the lode (ui_rock_rich). Run: python art/gen/wyrmhole.py art/sprites/ui_wyrmhole.toml"""
import math
import sys

PAL = {"O": "#2e1c2c", "K": "#1b0b3a", "D": "#52279c", "M": "#8a4ee0", "L": "#c08cff", "W": "#f3dcff", "S": "#ffffff"}
R = 5.9
C = 7.5
N = 6


def frame(k):
    fill = [[math.hypot(x - C, y - C) <= R for x in range(16)] for y in range(16)]
    g = [["."] * 16 for _ in range(16)]
    for y in range(16):
        for x in range(16):
            if not fill[y][x]:
                continue
            edge = any(not (0 <= x + dx < 16 and 0 <= y + dy < 16 and fill[y + dy][x + dx]) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
            if edge:
                g[y][x] = "O"
                continue
            r = math.hypot(x - C, y - C)
            th = math.atan2(y - C, x - C)
            if r < 1.4:
                g[y][x] = "K"
                continue
            # two arms; the spiral tightens toward the centre and the whole thing turns by 2*pi/2/N per frame (arms repeat every pi)
            v = (th - 0.85 * r - k * (math.pi / N)) % math.pi
            d = min(v, math.pi - v)
            if d < 0.38:
                g[y][x] = "W" if r > 3.4 and d < 0.17 else "L"
            elif d < 0.75:
                g[y][x] = "M"
            else:
                g[y][x] = "D"
    return g


lines = ["# Animated purple vortex for the wyrmhole cell. Generated by art/gen/wyrmhole.py.\n",
         "[ui_wyrmhole]", 'kind = "free"', "outline = false",
         "palette = { " + ", ".join(f'{a} = "{b}"' for a, b in PAL.items()) + " }", ""]
for k in range(N):
    lines += ["[[ui_wyrmhole.frames]]", "ms = 110", "rows = ["] + [f'  "{"".join(r)}",' for r in frame(k)] + ["]", ""]
open(sys.argv[1], "w").write("\n".join(lines))
