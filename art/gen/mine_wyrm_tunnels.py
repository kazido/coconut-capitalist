"""mine_wyrm_tunnels: a cut of rock (same frame as the other mine types) with a glowing purple wyrm burrow, a spiral tunnel, in the middle.
Run: python art/gen/mine_wyrm_tunnels.py art/sprites/mine_wyrm_tunnels.toml art/gen"""
import math
import sys

sys.path.insert(0, sys.argv[2])
from ui_icons import N, blank, put, rect  # noqa: E402

g = blank()
rect(g, 1, 2, 14, 14, "m"); rect(g, 1, 2, 14, 2, "H"); rect(g, 1, 2, 1, 14, "H"); rect(g, 14, 3, 14, 14, "s"); rect(g, 2, 14, 14, 14, "s")
for x, y in ((3, 4), (12, 4), (3, 12), (12, 12), (11, 13)):
    put(g, x, y, "s")
C = 7.5
for y in range(3, 14):
    for x in range(2, 14):
        r = math.hypot(x - C, y - 8.2)
        if r > 5.0:
            continue
        if r > 4.1:
            put(g, x, y, "G")  # glowing rim
            continue
        if r < 1.2:
            put(g, x, y, "k"); continue
        th = math.atan2(y - 8.2, x - C)
        v = (th - 0.9 * r) % math.pi
        d = min(v, math.pi - v)
        put(g, x, y, "L" if d < 0.4 else ("M" if d < 0.85 else "D"))
for x, y in ((6, 6), (10, 10)):
    pass
put(g, 6, 5, "W")  # glint top-left on the rim

pal = {"H": "#b8aab0", "m": "#857680", "s": "#5a4c58", "k": "#120c16", "G": "#c08cff", "L": "#e6c8ff", "M": "#8a4ee0", "D": "#3a1a78", "W": "#ffffff"}
used = {c for row in g for c in row if c != "."}
out = ["# mine_wyrm_tunnels. Generated by art/gen/mine_wyrm_tunnels.py.\n", "[mine_wyrm_tunnels]", 'kind = "free"', "outline = true",
       "palette = { " + ", ".join(f'{k} = "{v}"' for k, v in pal.items() if k in used) + " }", "rows = ["]
out += [f'  "{"".join(r)}",' for r in g] + ["]\n"]
open(sys.argv[1], "w").write("\n".join(out))
