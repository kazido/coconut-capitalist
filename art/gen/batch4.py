"""Batch 4: animated action icons for the skill pages. Writes art/sprites/ui_actions4.toml.

Run from the repo root: python art/gen/batch4.py
ui_chop_tree (Chop a tree), ui_harvest (Harvest all), ui_cast (Cast), ui_bobber (the line is in the water).
"""
import math
import sys

sys.path.insert(0, ".")
from art.draw import Canvas, circ, ell  # noqa: E402

N = 16
out = ["# Batch 4 skill action icons (animated). Generated by art/gen/batch4.py; edit the script, not this file.\n"]


def emit(name, pal, frames):
    used = {ch for g, _ in frames for row in g for ch in row if ch != "."}
    missing = used - set(pal)
    if missing:
        raise ValueError(f"{name}: no colour for {sorted(missing)}")
    out.extend([f"[{name}]", 'kind = "free"', "outline = true",
                "palette = { " + ", ".join(f'{k} = "{v}"' for k, v in pal.items() if k in used) + " }", ""])
    for g, ms in frames:
        out.extend([f"[[{name}.frames]]", f"ms = {ms}", "rows = ["] + [f'  "{"".join(r)}",' for r in g] + ["]", ""])


def copy(g):
    return [r[:] for r in g]


def put(g, x, y, ch):
    if 0 <= x < N and 0 <= y < N:
        g[y][x] = ch


def sparkle(g, x, y, core="W", arm="Y"):
    g = copy(g)
    put(g, x, y, core)
    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        put(g, x + dx, y + dy, arm)
    return g


# ---------------------------------------------------------------- Chop a tree: an axe swings in sideways, bites the trunk, the canopy shakes and a leaf drops.
def tree(c, shake, notch):
    c.fill(lambda x, y: 10 <= x <= 12 and 8 <= y <= 14, "T")  # a slim trunk
    c.fill(lambda x, y: x == 10 and 8 <= y <= 14, "U")
    c.fill(lambda x, y: x == 12 and 8 <= y <= 14, "t")
    c.put(9, 14, "U"); c.put(13, 14, "t")  # roots
    c.put(11, 12, "t")  # bark mark
    cx = 11 + shake
    crown = lambda x, y: circ(cx - 2, 5.5, 2.4)(x, y) or circ(cx + 1.8, 5, 2.5)(x, y) or circ(cx, 2.6, 2.3)(x, y)
    c.shade(crown, "LLlg", cx=cx, cy=4.5, r=3.5)  # a cloud of three leafy lumps
    for x, y in ((cx - 2, 6), (cx + 1, 3), (cx + 2, 6), (cx - 1, 4)):
        if c.g[y][x] in "Ll":
            c.put(x, y, "g" if c.g[y][x] == "l" else "l")  # leaf texture
    if notch:
        c.put(10, 11, "k"); c.put(10, 12, "k"); c.put(11, 12, "W")


def axe(c, o, lift=0):
    """The classic axe profile: a diagonal handle and a fanned blade whose edge faces the tree."""
    hx, hy = 7 + o, 10 - lift  # the eye of the head
    c.line(hx - 1, hy + 1, hx - 5, hy + 4, "H"); c.put(hx - 5, hy + 4, "h")  # handle, down to the left
    c.put(hx, hy - 1, "H")  # the handle's tip pokes through the eye
    c.put(hx - 1, hy, "s"); c.put(hx, hy, "s")  # poll and eye
    c.rect(hx + 1, hy - 1, hx + 1, hy + 1, "s")
    c.rect(hx + 2, hy - 2, hx + 2, hy + 2, "s")
    c.rect(hx + 3, hy - 2, hx + 3, hy + 2, "S")  # the cutting edge
    c.put(hx + 2, hy - 3, "S"); c.put(hx + 2, hy + 3, "S")  # the toe and the beard flare out


GRIP = (2, 14)  # the end of the handle: the swing turns around it


def swung_axe(deg):
    """The axe turned `deg` degrees back (counter-clockwise) around its grip; 0 = the blade in the trunk."""
    flat = Canvas()
    axe(flat, 0)
    a = math.radians(deg)
    g = [["." for _ in range(N)] for _ in range(N)]
    for y in range(N):
        for x in range(N):  # sample backwards so the turned axe has no holes
            dx, dy = x - GRIP[0], y - GRIP[1]
            sx = round(GRIP[0] + dx * math.cos(a) - dy * math.sin(a))
            sy = round(GRIP[1] + dx * math.sin(a) + dy * math.cos(a))
            if 0 <= sx < N and 0 <= sy < N and flat.g[sy][sx] in "sS":  # only the chunky head is sampled
                g[y][x] = flat.g[sy][sx]
    ex, ey = 5, -4  # the eye, from the grip; the thin handle is drawn as a clean line instead of rotated pixels
    tx = round(GRIP[0] + ex * math.cos(a) + ey * math.sin(a))
    ty = round(GRIP[1] - ex * math.sin(a) + ey * math.cos(a))
    c = Canvas(); c.g = g
    c.line(GRIP[0], GRIP[1], tx, ty, "H"); c.put(GRIP[0], GRIP[1], "h")
    return c.g


def smear(c, frm, to):
    """A pale arc where the blade's edge just travelled."""
    r, base = math.hypot(8, 4), math.degrees(math.atan2(4, 8))
    for k in range(int(min(frm, to)), int(max(frm, to)) + 1, 3):
        a = math.radians(base + k)
        x, y = round(GRIP[0] + r * math.cos(a)), round(GRIP[1] - r * math.sin(a))
        if 0 <= x < N and 0 <= y < N and c.g[y][x] == ".":  # the trail stays behind the tree
            c.put(x, y, "M")


def chop(deg, notch=False, shake=0, chips=0, leaf=None, trail=None):
    c = Canvas()
    tree(c, shake, notch)
    if trail:
        smear(c, *trail)
    g = swung_axe(deg)
    for y in range(N):
        for x in range(N):
            if g[y][x] != ".":
                c.put(x, y, g[y][x])
    for i in range(chips):
        c.put(8 - i * 2, 9 - i * 2, "C"); c.put(9 - i, 7 - i * 2, "C")
    if leaf:
        c.put(*leaf, "l")
    return c.g


ct = [(chop(48), 320), (chop(24, trail=(48, 24)), 60), (chop(0, notch=True, shake=1, trail=(24, 2)), 80),
      (chop(0, notch=True, chips=1), 90), (chop(0, notch=True, chips=2, leaf=(14, 10)), 120),
      (chop(20, notch=True, leaf=(14, 12)), 140), (chop(40, notch=True), 160)]
emit("ui_chop_tree", {"T": "#9a6a44", "U": "#c8905a", "t": "#6a4428", "k": "#2e1c2c", "W": "#f0c890", "C": "#fff0c8",
                      "L": "#8ee05a", "l": "#4ea03c", "g": "#2c6a30", "H": "#c8905a", "h": "#7a4c30", "S": "#f4f8ff",
                      "s": "#8a96ac", "M": "#d8e8ff"}, ct)


# ---------------------------------------------------------------- Harvest: a carrot drops into a woven basket of crops.
def basket(c, squash=0):
    top = 8 + squash
    for y in range(top, 15):
        inset = (y - top) * 0.25
        for x in range(N):
            if 2 + inset <= x <= 13 - inset:
                c.put(x, y, "B" if (x + y) % 2 else "b")
                if x >= 12 - inset:
                    c.put(x, y, "b")
    c.rect(2, top, 13, top, "R"); c.put(13, top, "r")


def harvest(cy, landed=False, shine=False):
    c = Canvas()
    c.fill(lambda x, y: ell(5, 5, 1.6, 3.2)(x, y), "y")  # a corn cob on the left
    c.fill(lambda x, y: ell(5, 5, 1.6, 3.2)(x, y) and (x + y) % 2 == 0, "Y")
    c.put(3, 6, "G"); c.put(3, 7, "G"); c.put(7, 7, "g")  # its husk
    c.shade(circ(10.5, 6.2, 1.7), "QQqq", cx=10.5, cy=6.2, r=1.7)  # a tomato on the right
    c.put(10, 4, "G")
    if cy is not None:  # the carrot, point down
        for i, w in enumerate((1, 1, 0, 0)):
            c.rect(7, cy + i, 7 + w, cy + i, "O" if i < 2 else "o")
        c.put(7, cy - 1, "G"); c.put(8, cy - 2, "G")
    basket(c, 1 if landed else 0)
    g = c.g
    if shine:
        g = sparkle(g, 12, 2, arm="Y")
    return g


hv = [(harvest(0), 220), (harvest(2), 70), (harvest(5), 70), (harvest(None, landed=True), 90), (harvest(None), 160),
      (harvest(None, shine=True), 160), (harvest(None), 300)]
emit("ui_harvest", {"B": "#d8a060", "b": "#a8703a", "R": "#f0c080", "r": "#a8703a", "Y": "#fff2a0", "y": "#e8b838",
                    "Q": "#ff6a5a", "q": "#c03a3a", "G": "#5ac04a", "g": "#2c7a34", "O": "#ffa040", "o": "#d86a20", "W": "#ffffff"}, hv)


# ---------------------------------------------------------------- Cast: a proper rod (cork grip, reel, bending blank) whips forward; the bobber sails out and splashes.
def rod(c, base, bend, n=9):
    """Draw the rod from the grip at the bottom left, bending `bend` degrees a pixel along the blank. Returns the tip."""
    x, y, d = 2.0, 14.0, base
    for i in range(3 + n):
        px, py = round(x), round(y)
        if i < 3:  # cork grip, two pixels thick
            c.put(px, py, "W"); c.put(px + 1, py, "w")
        else:
            c.put(px, py, "R")
            d += bend
        if i == 3:  # the reel sits under the rod
            c.put(px + 1, py + 1, "k"); c.put(px + 2, py + 1, "K")
        x += math.cos(math.radians(d)); y -= math.sin(math.radians(d))
    return round(x - math.cos(math.radians(d))), round(y + math.sin(math.radians(d)))


def cast(base, bend, bob, splash=0):
    c = Canvas()
    if splash:
        c.rect(9, 14, 14, 14, "a")
    tx, ty = rod(c, base, bend)
    bx, by = bob
    c.line(tx, ty, bx, by, "l")
    if splash:
        for x, y in ((10, 12), (14, 12), (11, 11), (13, 11)) if splash == 1 else ((9, 13), (14, 13)):
            c.put(x, y, "a")
    c.put(bx, by, "F"); c.put(bx + 1, by, "F"); c.put(bx, by + 1, "f"); c.put(bx + 1, by + 1, "f")
    return c.g


cs = [(cast(95, 3, (2, 4)), 280), (cast(70, 5, (1, 2)), 60), (cast(52, -3, (11, 1)), 80), (cast(50, -4, (13, 6)), 80),
      (cast(50, -4, (12, 11), splash=1), 120), (cast(50, -4, (12, 12), splash=2), 400)]
emit("ui_cast", {"W": "#e0b080", "w": "#9a6a44", "R": "#6a4a3a", "k": "#4a4250", "K": "#a8a0b0", "l": "#d8e4f0",
                 "F": "#ff5a4a", "f": "#f4f0ec", "a": "#8ad8ff"}, cs)


# ---------------------------------------------------------------- Bobber: floating in the water, bobbing, ripples spreading.
def bobber(dy, ripple, phase):
    c = Canvas()
    c.fill(lambda x, y: 11 <= y <= 14 and 1 <= x <= 14, "A")  # water
    c.fill(lambda x, y: 13 <= y <= 14 and 1 <= x <= 14, "a")
    for x in range(1, 15):  # a rolling surface: crests move one pixel a frame
        if (x + phase) % 4 == 0:
            c.put(x, 10, "C")
        if (x + phase) % 4 in (0, 1):
            c.put(x, 11, "C")
    by = 5 + dy
    m = ell(7.5, by + 3, 2.6, 3.0)
    c.fill(lambda x, y: m(x, y) and y <= by + 2, "F")  # red cap
    c.fill(lambda x, y: m(x, y) and by + 3 <= y <= 10, "f")  # white belly
    c.fill(lambda x, y: m(x, y) and y >= 11, "d")  # seen through the water
    c.put(6, by + 1, "H")
    c.rect(7, 1, 7, by - 1, "l")  # the line
    if ripple:
        for x in (5 - ripple, 10 + ripple):
            c.put(x, 11, "W")
    return c.g


bb = [(bobber(0, 0, 0), 300), (bobber(1, 1, 1), 220), (bobber(1, 2, 2), 220), (bobber(0, 3, 3), 260)]
emit("ui_bobber", {"A": "#3a8ad8", "a": "#2a5aa8", "C": "#8ad8ff", "W": "#ffffff", "F": "#ff5a4a", "f": "#f4f0ec",
                   "H": "#ffc0b0", "l": "#d8e4f0", "d": "#8ab0d8"}, bb)

open("art/sprites/ui_actions4.toml", "w").write("\n".join(out))
print("wrote", sum(1 for line in out if line.startswith("[ui_")), "sprites")
