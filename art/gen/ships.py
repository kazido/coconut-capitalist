"""Ship tier icons (ship_<slug>), animated: every ship bobs and has one moving detail.

Run from the repo root: python art/gen/ships.py art/sprites/ships.toml
Each ship is drawn once (`base`), then every frame is the base plus a per-frame overlay
(fluttering sail, rising smoke, twinkling star, a glow running along the void runner's stripe).
"""
import sys

sys.path.insert(0, ".")
from art.draw import Canvas, circ, ell  # noqa: E402

BOB = [0, 0, 0, 0]  # ships do not bob (owner): only sails, smoke, stars and glows move
MS = 200
out = ["# Ship tier icons (ship_<slug>), animated. Generated by art/gen/ships.py: edit that, never this file.", ""]


def poly(pts):
    """Point-in-polygon mask (pixel centres)."""
    def m(x, y):
        px, py, inside = x + 0.5, y + 0.5, False
        j = len(pts) - 1
        for i in range(len(pts)):
            xi, yi = pts[i]
            xj, yj = pts[j]
            if (yi > py) != (yj > py) and px < (xj - xi) * (py - yi) / (yj - yi) + xi:
                inside = not inside
            j = i
        return inside
    return m


def grab(c):
    g = [row[:] for row in c.g]
    c.g = [["." for _ in range(16)] for _ in range(16)]
    return g


def shift(g, dy):
    o = [["." for _ in range(16)] for _ in range(16)]
    for y in range(16):
        for x in range(16):
            if g[y][x] != "." and 0 <= y + dy < 16:
                o[y + dy][x] = g[y][x]
    return o


def put(g, x, y, ch):
    if 0 < x < 15 and 0 < y < 15:
        g[y][x] = ch


def draw_on(g, fn):
    """Run `fn(canvas)` on a copy of frame `g` (so per-frame shapes like a billowing sail use the same Canvas helpers)."""
    c2 = Canvas()
    c2.g = [row[:] for row in g]
    fn(c2)
    g[:] = c2.g


def emit(name, pal, frames):
    used = {ch for f in frames for row in f for ch in row if ch != "."}
    out.extend([f"[{name}]", 'kind = "free"', "outline = true",
                "palette = { " + ", ".join(f'{k} = "{v}"' for k, v in pal.items() if k in used) + " }", ""])
    for f in frames:
        out.extend([f"[[{name}.frames]]", f"ms = {MS}", "rows = ["] + [f'  "{"".join(r)}",' for r in f] + ["]", ""])


def animate(base, overlay, bob=BOB):
    frames = []
    for t, dy in enumerate(bob):
        g = shift(base, dy)
        overlay(g, t, dy)
        frames.append(g)
    return frames


c = Canvas()

# 1. Patchwork Raft: lashed logs, a crooked mast, a patched sail whose loose corner flutters
c.shade(poly([(2, 11), (14, 11), (14, 14), (2, 14)]), "LWwB", 7, 11, 4)
for x in (5, 9):
    c.line(x, 11, x, 13, "B")
c.rect(2, 12, 13, 12, "R")
c.line(7, 2, 7, 10, "B")
raft = grab(c)
RAFT_SAIL = [[(8, 3), (13, 5), (13, 10), (8, 10)], [(8, 3), (14, 5), (14, 8), (13, 10), (8, 10)],
             [(8, 3), (14, 6), (14, 9), (8, 10)], [(8, 3), (13, 5), (14, 8), (12, 10), (8, 10)]]  # the wind fills and drops


def raft_fx(g, t, dy):
    def sail(cv):
        cv.shade(poly(RAFT_SAIL[t]), "CcK", 9, 4, 5)
        cv.rect(10, 6, 11, 7, "P")
        cv.put(9, 9, "G")
    draw_on(g, sail)


emit("ship_patchwork_raft", {"L": "#d8a868", "W": "#a8743c", "w": "#7c5028", "B": "#553218", "R": "#e0cc90", "C": "#f4ead0",
                             "c": "#d8c8a0", "K": "#a8946c", "P": "#c8484c", "G": "#5c9c4c"}, animate(raft, raft_fx))

# 2. Dune Skiff: a sand-gold hull, a tall orange sail that billows
c.shade(poly([(1, 11), (15, 11), (12, 14), (4, 14)]), "YyuU", 6, 11, 5)
c.line(3, 14, 13, 14, "U")
c.line(8, 2, 8, 10, "B")
skiff = grab(c)
SKIFF_MAIN = [[(9, 3), (14, 9), (9, 10)], [(9, 3), (13, 5), (14, 9), (9, 10)],
              [(9, 3), (14, 6), (14, 9), (9, 10)], [(9, 3), (13, 6), (13, 9), (9, 10)]]
SKIFF_FORE = [[(7, 5), (7, 10), (3, 10)], [(7, 5), (7, 10), (2, 10)], [(7, 5), (7, 10), (2, 9)], [(7, 5), (7, 10), (3, 10)]]


def skiff_fx(g, t, dy):
    def sails(cv):
        cv.shade(poly(SKIFF_MAIN[t]), "OoQ", 10, 5, 5)
        cv.shade(poly(SKIFF_FORE[t]), "OoQ", 6, 7, 4)
    draw_on(g, sails)


emit("ship_dune_skiff", {"Y": "#f4dc8c", "y": "#d8b460", "u": "#a87c3c", "U": "#6c4c24", "B": "#553218", "O": "#ffb050",
                         "o": "#e8782c", "Q": "#a84c1c"}, animate(skiff, skiff_fx))

# 3. Scrap Cruiser: heavy, it does not bob; it chugs smoke puffs that rise and drift back
c.shade(poly([(1, 10), (15, 10), (13, 14), (3, 14)]), "SsgG", 6, 10, 5)
c.line(2, 12, 14, 12, "R")
for x in (4, 7, 10, 13):
    c.put(x, 11, "H")
c.shade(poly([(4, 6), (10, 6), (10, 9), (4, 9)]), "SsgG", 5, 6, 4)
c.put(6, 7, "W")
c.put(8, 7, "W")
c.shade(poly([(11, 4), (13, 4), (13, 9), (11, 9)]), "Rrq", 11, 4, 4)
cruiser = grab(c)
PUFFS = [[(12, 3)], [(12, 2), (11, 3)], [(11, 1), (12, 2), (10, 2)], [(10, 1), (9, 1)]]  # rising, spreading, thinning


def cruiser_fx(g, t, dy):
    for x, y in PUFFS[t]:
        put(g, x, y, "M" if t < 3 else "m")
    if t == 2:
        put(g, 8, 7, "w")  # a porthole flickers


emit("ship_scrap_cruiser", {"S": "#c8ccd0", "s": "#9098a0", "g": "#646c78", "G": "#3c4250", "R": "#d0703c", "r": "#a04c28",
                            "q": "#6c301c", "H": "#e8ecf0", "W": "#ffe890", "w": "#c8a850", "M": "#e0e0e4", "m": "#a8a8b0"},
     animate(cruiser, cruiser_fx))

# 4. Sky Frigate: the only ship that bobs (it flies); the little wings beat
c.shade(ell(7.5, 5.0, 6.2, 3.2), "VvnN", 6, 4, 5)
for x in (5, 10):
    c.line(x, 3, x, 7, "T")
c.line(4, 8, 5, 10, "B")
c.line(11, 8, 10, 10, "B")
c.shade(poly([(3, 10), (13, 10), (11, 14), (5, 14)]), "LWwB", 7, 10, 4)
c.line(5, 12, 11, 12, "Y")
frigate = grab(c)


def frigate_fx(g, t, dy):
    up = t in (1, 2)
    for x0, sign in ((1, 1), (14, -1)):  # wings: spread level, then tipped up
        put(g, x0, (10 if up else 11) + dy, "C")
        put(g, x0 + sign, 11 + dy, "C")
        put(g, x0 + sign * 2, 12 + dy, "C")


emit("ship_sky_frigate", {"V": "#ff8a80", "v": "#e0484c", "n": "#a8303c", "N": "#6c1c2c", "L": "#d8a868", "W": "#a8743c",
                          "w": "#7c5028", "B": "#553218", "Y": "#ffd34c", "C": "#e8f0f8", "T": "#ffc8c0"}, animate(frigate, frigate_fx, [0, -1, -1, 0]))

# 5. Star Clipper: slim navy hull, pale sails, the star on the mainmast twinkles
c.shade(poly([(1, 11), (15, 10), (13, 14), (3, 14)]), "IiJj", 6, 11, 5)
c.line(3, 12, 13, 12, "Y")
clipper = grab(c)
# Three sails billow one after another (a wave from bow to stern): (polygon flat, polygon bellied, light centre)
CLIPPER_SAILS = [([(7, 5), (9, 6), (9, 10), (7, 10)], [(7, 5), (9, 6), (10, 8), (9, 10), (7, 10)], (7, 5)),
                 ([(11, 6), (13, 7), (13, 10), (11, 10)], [(11, 6), (13, 7), (14, 8), (13, 10), (11, 10)], (11, 6)),
                 ([(3, 6), (5, 5), (5, 10), (3, 10)], [(3, 6), (5, 5), (6, 8), (5, 10), (3, 10)], (3, 5))]


def clipper_fx(g, t, dy):
    def sails(cv):
        for i, (flat, full, (lx, ly)) in enumerate(CLIPPER_SAILS):
            cv.shade(poly(full if (t + i) % 4 in (1, 2) else flat), "Ccx", lx, ly, 4)
        cv.line(6, 5, 6, 10, "B")
        cv.line(10, 5, 10, 10, "B")  # masts in front of the bellied sails
    draw_on(g, sails)
    cy = 3 + dy
    for x, y in ((6, cy - 1), (5, cy), (6, cy), (7, cy), (6, cy + 1)):
        put(g, x, y, "Y")
    put(g, 6, cy, "Z")
    if t in (1, 2):  # flare: longer arms and a white glint
        for x, y in ((4, cy), (8, cy)):
            put(g, x, y, "y")
        put(g, 6, cy - 1, "Z")


emit("ship_star_clipper", {"I": "#6c84d8", "i": "#4458b0", "J": "#2c3480", "j": "#1c1c50", "Y": "#ffd34c", "y": "#c89c2c",
                           "Z": "#fff8d0", "B": "#8c6c40", "C": "#f0f4ff", "c": "#c8d0f0", "x": "#9098c8"}, animate(clipper, clipper_fx))

# 6. Void Runner: the dark whale-like hull (owner's favourite first draft); a glow runs along its gradient stripe
c.shade(poly([(1, 10), (6, 7), (14, 8), (15, 11), (12, 13), (3, 13)]), "DdEe", 6, 8, 5)
c.shade(poly([(7, 7), (10, 2), (11, 2), (11, 8)]), "DdEe", 9, 3, 4)
c.put(9, 9, "W")
c.put(11, 9, "W")
runner = grab(c)
STRIPE = list(range(3, 14))
GRAD = "aabbbVVVhhh"  # dark violet at the stern -> bright at the bow (the base gradient)


SHEEN = [0, 1, 2, 1]  # the hull's lit patch slides back and forth a little: the ship is gliding


def runner_fx(g, t, dy):
    lit = [(x, y) for y in range(16) for x in range(16) if runner[y][x] == "D"]
    for x, y in lit:
        put(g, x, y + dy, "d")
    for x, y in lit:
        if runner[y][min(x + SHEEN[t], 15)] in "Dd":
            put(g, x + SHEEN[t], y + dy, "D")
    for i, x in enumerate(STRIPE):
        put(g, x, 11 + dy, GRAD[i])
    for x in (3 + t * 3, 4 + t * 3):  # a bright pulse travels from stern to bow
        put(g, x, 11 + dy, "Z")
    put(g, 1, 11 + dy, "V")  # steady engine glow (only the stripe moves)


emit("ship_void_runner", {"D": "#7c6c9c", "d": "#4c4070", "E": "#2c2448", "e": "#1a1430", "a": "#6a2cb8", "b": "#8c44e8",
                          "V": "#b45cff", "h": "#d4a0ff", "W": "#e0c8ff", "Z": "#f8eeff"}, animate(runner, runner_fx))

open(sys.argv[1], "w", encoding="utf-8").write("\n".join(out))
