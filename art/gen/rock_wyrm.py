"""ui_rock_wyrm: the firm-rock icon recoloured cosmic purple, animated (a light band sweeps across, stars twinkle).
Run: python art/gen/rock_wyrm.py art/sprites/ui_rock_wyrm.toml
Base shape = ui_rock_firm (raven pack cell) quantised to 16x16 and recoloured with a 4-tone ramp (O outline, W/L/M/D light..dark)."""
import sys

BASE = [
    "................",
    "................",
    "......OOOO......",
    ".....OLLLLO.....",
    "....OLMMMMO.....",
    "...OLMMMMMMO....",
    "...OLLMMMMLDO...",
    "...ODDLMMLDDO...",   # (W highlight pixels are added below)
    "...ODDDLLDDDO...",
    "...ODDDLDDDDO...",
    "....ODDDDDDO....",
    ".....ODDDDO.....",
    "......ODDO......",
    ".......OO.......",
    "................",
    "................",
]
# tone shift one step lighter on the sweeping band
LIGHTER = {"D": "M", "M": "L", "L": "W"}
PAL = {"O": "#2e1c2c", "W": "#f3dcff", "L": "#c08cff", "M": "#8a4ee0", "D": "#52279c",
       "S": "#ffffff", "C": "#7af0ff", "P": "#ff8ae6"}

def grid():
    g = [list(r) for r in BASE]
    for x, y in ((5, 4), (4, 5)):   # the crystal glint, as in the original
        g[y][x] = "W"
    return g

def frame(k, n):
    g = grid()
    # sweeping light band along x+y, 2 wide, moves down-right across the rock
    centre = 6 + k * (14 / n)
    for y in range(16):
        for x in range(16):
            if g[y][x] in LIGHTER and abs((x + y) - centre) < 1.2:
                g[y][x] = LIGHTER[g[y][x]]
    # twinkling stars: inside the rock (alternate colours) and two out in the margin
    inside = [(7, 6, "C"), (9, 8, "P"), (6, 9, "C"), (10, 5, "P")]
    for i, (x, y, ch) in enumerate(inside):
        if (k + i) % n in (0, 1):
            g[y][x] = "S" if (k + i) % n == 0 else ch
    out = [(2, 4), (13, 9), (11, 2)]
    for i, (x, y) in enumerate(out):
        phase = (k + 2 * i) % n
        if phase == 0:
            g[y][x] = "S"
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                if g[y + dy][x + dx] == ".":
                    g[y + dy][x + dx] = "C" if i % 2 == 0 else "P"
        elif phase == 1:
            g[y][x] = "C" if i % 2 == 0 else "P"
    return g

n = 6
lines = ["# Cosmic purple recolour of ui_rock_firm, animated. Generated by art/gen/rock_wyrm.py.\n",
         "[ui_rock_wyrm]", 'kind = "free"', "outline = false",
         "palette = { " + ", ".join(f'{k} = "{v}"' for k, v in PAL.items()) + " }", ""]
for k in range(n):
    lines += ["[[ui_rock_wyrm.frames]]", "ms = 130", "rows = ["] + [f'  "{"".join(r)}",' for r in frame(k, n)] + ["]", ""]
open(sys.argv[1], "w").write("\n".join(lines))
