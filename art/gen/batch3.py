def outline(g, ch="o"):
    """Draw the plum outline ourselves (4-neighbour, like the build) so the laser beams can glow without one."""
    o = copy(g)
    for y in range(N):
        for x in range(N):
            if g[y][x] == "." and any(0 <= x + dx < N and 0 <= y + dy < N and g[y + dy][x + dx] not in ".o"
                                      for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                o[y][x] = ch
    return o


