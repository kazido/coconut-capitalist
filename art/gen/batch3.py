# Farming: the husks peel back from the cob, it shines, then they close up again.
def corn(p, shine=False):
    g = blank()
    for y in range(1, 12):
        w = 2.7 * math.sqrt(max(0.0, 1 - ((y - 6.5) / 5.9) ** 2))
        for x in range(N):
            if abs(x - 7.5) <= w + 0.2:
                rel = (x - 7.5) / max(w, 0.5)
                c = 0 if rel < -0.35 else 1 if rel < 0.45 else 2
                if y % 2 == 0 and x % 2 == 1:
                    c = min(c + 1, 3)
                put(g, x, y, "Eedc"[c])
    top = 1 + 5 * p  # how far the husks have peeled down
    for y in range(N):
        if y < top or y > 14:
            continue
        w = 2.7 * math.sqrt(max(0.0, 1 - ((y - 6.5) / 5.9) ** 2))
        for side in (-1, 1):
            outer_open = 3 + abs(y - 10) * 0.7 if side < 0 else 12 - abs(y - 10) * 0.7
            inner_open = 5.6 + (y - 6) * 0.3 if side < 0 else 9.4 - (y - 6) * 0.3
            outer_closed = 7.5 + side * (w + 0.8) if y < 10 else outer_open
            inner_closed = 7.5
            a = (1 - p) * outer_closed + p * outer_open
            b = (1 - p) * inner_closed + p * inner_open
            lo, hi = min(a, b), max(a, b)
            for x in range(N):
                if lo <= x <= hi:
                    left = x < (lo + hi) / 2
                    put(g, x, y, ("L" if left else "l") if side < 0 else ("m" if left else "s"))
    if shine:
        g = sparkle(g, 6, 3, core="W", arm="E")
    return g
