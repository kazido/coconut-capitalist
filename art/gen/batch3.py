def rock(c, r=1.0, ghost=False, cracks=False, cx=7.5, cy=11.5):
    c.shade(ell(cx, cy, 3.6 * r, 2.8 * r), "QqPp" if ghost else "RrUu", cx=cx, cy=cy, r=3.5)
    if not ghost and r >= 1:
        for x, y in ((6, 11), (9, 12), (7, 13), (9, 10)):
            c.put(x, y, "Y" if (x + y) % 2 else "y")
    if cracks:
        for x, y in ((7, 9), (8, 10), (7, 11), (8, 12), (7, 13), (5, 11), (10, 11)):
            c.put(x, y, "k")


def beams(g, to=(7, 11)):
    for sx, sy in ((2, 8), (13, 8)):
        n = max(abs(to[0] - sx), abs(to[1] - sy))
        for i in range(n):
            x, y = round(sx + (to[0] - sx) * i / n), round(sy + (to[1] - sy) * i / n)
            if g[y][x] in ".o":
                g[y][x] = "B"
    return g


def am_frame(stage):
    base = rig("L" if stage in ("beam1", "beam2", "beam3") else "l")
    c = Canvas(); c.g = base
    if stage == "beam2":
        rock(c, 0.5, ghost=True)
    elif stage == "beam3":
        rock(c, 0.9, ghost=True)
    elif stage in ("solid", "crack"):
        rock(c, cracks=stage == "crack")
    elif stage.startswith("shatter"):
        gap = int(stage[-1])
        tmp = Canvas(); rock(tmp)
        for y in range(N):
            for x in range(N):
                if tmp.g[y][x] != "." and (gap == 1 or (x + y) % 3):
                    put(c.g, x + (-gap if x < 8 else gap), y + (-1 if y < 11 else 1) * (gap - 1), tmp.g[y][x])
    g = outline(c.g)
    if stage.startswith("beam"):
        g = beams(g)
        if stage == "beam1":
            g = sparkle(g, 7, 11, core="W", arm="B")
    if stage == "shatter1":
        g = sparkle(g, 7, 11, True, core="W", arm="Y")
    return g


