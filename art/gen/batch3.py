    for fr in fronds:
        for k, (fx, fy) in enumerate(fr):
            x, y = cx + fx, cy + fy
            c.put(x, y, "L")
            if k < 3:
                c.put(x, y + 1, "l")
    c.put(cx, cy, "l")
    c.put(cx - 1, cy + 1, "K"); c.put(cx, cy + 1, "k")  # coconuts under the crown
    return c.g


