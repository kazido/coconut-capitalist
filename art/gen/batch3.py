# ---------------------------------------------------------------- Skills, animated.
def rotate(g, deg, px, py, keep=None):
    """Turn the grid `deg` clockwise around (px, py) (nearest pixel, no holes). `keep(x, y)` pixels stay put."""
    a = math.radians(deg)
    o = blank()
    for y in range(N):
        for x in range(N):
            if keep and keep(x, y):
                o[y][x] = g[y][x]
                continue
            dx, dy = x - px, y - py
            sx, sy = px + dx * math.cos(a) + dy * math.sin(a), py - dx * math.sin(a) + dy * math.cos(a)
            sx, sy = round(sx), round(sy)
            if 0 <= sx < N and 0 <= sy < N and g[sy][sx] != "." and not (keep and keep(sx, sy)):
                o[y][x] = g[sy][sx]
    return o


