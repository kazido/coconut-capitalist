def emit(name, pal, frames, outline=True):
    """frames: a grid, or a list of (grid, ms) for an animation."""
    anim = isinstance(frames, list) and isinstance(frames[0], tuple)
    grids = [f for f, _ in frames] if anim else [frames]
    used = {ch for g in grids for row in g for ch in row if ch != "."}
    missing = used - set(pal)
    if missing:
        raise ValueError(f"{name}: no colour for {sorted(missing)}")
    out.extend([f"[{name}]", 'kind = "free"', f"outline = {'true' if outline else 'false'}",
                "palette = { " + ", ".join(f'{k} = "{v}"' for k, v in pal.items() if k in used) + " }"])
    if anim:
        out.append("")
        for g, ms in frames:
            out.extend([f"[[{name}.frames]]", f"ms = {ms}", "rows = ["] + [f'  "{"".join(r)}",' for r in g] + ["]", ""])
    else:
        out.extend(["rows = ["] + [f'  "{"".join(r)}",' for r in frames] + ["]\n"])


def blank():
    return [["." for _ in range(N)] for _ in range(N)]


def copy(g):
    return [r[:] for r in g]


def shift(g, dx, dy, rows=None):
    """Move the whole grid (or only `rows`) by dx, dy."""
    o = copy(g) if rows else blank()
    if rows:
        for y in rows:
            o[y] = ["."] * N
    for y in range(N):
        if rows and y not in rows:
            continue
        for x in range(N):
            if g[y][x] != "." and 0 <= x + dx < N and 0 <= y + dy < N:
                o[y + dy][x + dx] = g[y][x]
    return o


def put(g, x, y, ch):
    if 0 <= x < N and 0 <= y < N:
        g[y][x] = ch


def sparkle(g, x, y, big=False, core="W", arm="Y"):
    g = copy(g)
    put(g, x, y, core)
    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        put(g, x + dx, y + dy, arm)
    if big:
        for dx, dy in ((2, 0), (-2, 0), (0, 2), (0, -2)):
            put(g, x + dx, y + dy, arm)
    return g


def rows_of(text):
    return [list(r) for r in text.split()]


def strip(g, ch="o"):
    return [[("." if c == ch else c) for c in r] for r in g]


# ---------------------------------------------------------------- Timer: round bulbs, a 2px neck; sand runs down, then it flips.
def hw(y):
    d = abs(y - 7.5)
    return 1.0 + 3.6 * math.sin(min(1.0, (d - 0.5) / 3.2) * math.pi / 2)


def hourglass(top_rows, bottom_rows, stream):
    c = Canvas()
    for y0 in (1, 13):  # wooden caps
        c.rect(2, y0, 13, y0, "A"); c.rect(2, y0 + 1, 13, y0 + 1, "a")
        c.put(13, y0, "a"); c.put(13, y0 + 1, "c")
    c.rect(2, 2, 13, 2, "a"); c.rect(2, 13, 13, 13, "A")
    for y in range(3, 13):
        w = hw(y)
        xs = [x for x in range(N) if abs(x - 7.5) <= w]
        for x in xs:
            sand = (y <= 7 and y > 7 - top_rows) or (y >= 8 and y > 12 - bottom_rows)
            if y >= 8 and y == 12 - bottom_rows + 1 and bottom_rows and abs(x - 7.5) > w - 1.2 and bottom_rows < 4:
                sand = False  # the pile is a mound: its top row is narrower
            edge_l, edge_r = x == xs[0], x == xs[-1]
            if sand:
                c.put(x, y, "S" if edge_l or x < 7 else "s" if not edge_r else "z")
            else:
                c.put(x, y, "g" if edge_l else "f" if edge_r else "e")
    if stream:
        for y in range(7, 13 - bottom_rows):
            c.put(7, y, "S")
    return c.g


