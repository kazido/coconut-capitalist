# ---------------------------------------------------------------- Magnet: rattles, then yanks two iron balls up onto its poles.
def magnet(ball_y, field, dx=0):
    c = Canvas()
    for y in range(N):
        for x in range(N):
            d = math.hypot(x - 7.5, y - 5.5)
            arch = 2.2 <= d <= 5.4 and y <= 5.5
            leg = 5.5 < y <= 9 and (2 <= x <= 4 or 11 <= x <= 13)
            if not (arch or leg):
                continue
            tip = y >= 8
            lit = x < 7.5 and (d > 4.4 or (y > 5.5 and x == 2))
            dark = x > 7.5 and (d < 3.2 or x == 13) or (y > 5.5 and x in (4, 13))
            c.put(x + dx, y, ("T" if lit else "t" if dark else "M") if tip else ("H" if lit else "r" if dark else "R"))
    for bx in (3, 12):  # a steel nut (with its hole) under each pole
        c.rect(bx - 1, ball_y, bx + 1, ball_y + 2, "N"); c.put(bx - 1, ball_y, "W"); c.put(bx + 1, ball_y + 2, "n")
        c.put(bx, ball_y + 1, "n")
        if field:  # motion streaks as they fly up
            c.put(bx - 1, ball_y + 3, "B"); c.put(bx + 1, ball_y + 3, "B")
    return c.g


