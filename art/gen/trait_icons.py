"""Smithing trait icons (unframed UI icons `ui_trait_<stat>`): power, scholar, appraise.
(rare_luck and drop_amount are Raven pack cells, see art/mappings/raven_magic.toml.)

Run: python art/gen/trait_icons.py art/sprites/traits.toml   (edit this file, never the TOML)
"""
import sys

sys.path.insert(0, ".")
from art.draw import Canvas, circ, ell, union  # noqa: E402
from art.gen.tool_layers import poly  # noqa: E402

GOLD = ["#fff2a8", "#ffcc3a", "#d08a14", "#8a5208"]
CREAM = ["#fffdf2", "#f0e4c8", "#cdbb92", "#9a875f"]
BLUE = ["#9ad8ff", "#4a9cff", "#2c64b8", "#1a3a70"]
GEM = ["#e4fbff", "#7fe0f0", "#2fa8d0", "#1a6290"]
WHITE = ["#ffffff"] * 4
LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"


class Art:
    """A Canvas that hands out palette letters per ramp, so one icon can mix materials."""

    def __init__(self):
        self.c = Canvas()
        self.pal: dict[str, str] = {}
        self.ramps: dict[tuple, str] = {}

    def _letters(self, ramp):
        key = tuple(ramp)
        if key not in self.ramps:
            ls = LETTERS[len(self.pal):len(self.pal) + 4]
            self.ramps[key] = ls
            self.pal.update(zip(ls, ramp))
        return self.ramps[key]

    def shade(self, mask, ramp, **kw):
        self.c.shade(mask, self._letters(ramp), **kw)

    def put(self, x, y, ramp, i):
        self.c.put(x, y, self._letters(ramp)[i])

    def fill(self, mask, ramp, i):
        self.c.fill(mask, self._letters(ramp)[i])

    def grid(self):
        return self.c.g, self.pal


def power():
    a = Art()  # a lightning bolt
    a.shade(poly([(6.5, 1), (12, 1), (9.4, 6.2), (13, 6.2), (5.5, 15), (7.3, 9.4), (3.5, 9.4)]), GOLD, cx=6, cy=3, r=9)
    return a.grid()


# Everything but the bolt is mirror-symmetric about x = 7.5 (every point x pairs with 15 - x).
def scholar():
    a = Art()  # an open book: blue cover, two cream pages split by a 2px spine, two faint text lines per page
    a.shade(poly([(0.8, 4), (7.5, 5.2), (14.2, 4), (14.2, 13), (7.5, 14.2), (0.8, 13)]), BLUE, cx=3, cy=5, r=10)
    a.shade(poly([(2, 4.6), (6.8, 5.8), (6.8, 12.6), (2, 11.6)]), CREAM, cx=3, cy=5, r=7)
    a.shade(poly([(13, 4.6), (8.2, 5.8), (8.2, 12.6), (13, 11.6)]), CREAM, cx=3, cy=5, r=14)
    for y in (8, 10):
        for x in (3, 4, 5, 10, 11, 12):
            a.put(x, y, CREAM, 3)
    return a.grid()


def appraise():
    a = Art()  # a brilliant-cut gem: lit left facets, shaded right facets, white glints on the crown
    a.fill(poly([(4, 3), (5, 3), (4, 6.5), (1, 6.5)]), GEM, 1)  # crown, left
    a.fill(poly([(11, 3), (10, 3), (11, 6.5), (14, 6.5)]), GEM, 2)  # crown, right
    a.fill(poly([(5, 3), (10, 3), (11, 6.5), (4, 6.5)]), GEM, 0)  # crown, table (brightest)
    a.fill(poly([(1, 6.5), (4, 6.5), (7.5, 14.5)]), GEM, 0)  # pavilion, outer left (catches the light)
    a.fill(poly([(14, 6.5), (11, 6.5), (7.5, 14.5)]), GEM, 3)  # outer right (darkest)
    a.fill(poly([(4, 6.5), (7.5, 6.5), (7.5, 14.5)]), GEM, 1)  # inner left
    a.fill(poly([(7.5, 6.5), (11, 6.5), (7.5, 14.5)]), GEM, 2)  # inner right
    for x in range(16):  # the girdle: a thin edge between crown and pavilion, so the two read as separate tiers
        if a.c.g[6][x] != ".":
            a.put(x, 6, GEM, 2 if x < 8 else 3)
    for x, y in ((6, 4), (7, 4), (6, 3)):  # a bright glint on the table
        a.put(x, y, WHITE, 0)
    return a.grid()


TRAITS = {"ui_trait_power": power, "ui_trait_scholar": scholar, "ui_trait_appraise": appraise}


def section(name, g, pal):
    used = {ch for row in g for ch in row if ch != "."}
    return [f"[{name}]", 'kind = "free"', "outline = true",
            "palette = { " + ", ".join(f'{k} = "{v}"' for k, v in pal.items() if k in used) + " }",
            "rows = ["] + [f'  "{"".join(r)}",' for r in g] + ["]", ""]


if __name__ == "__main__":
    lines = ["# Smithing trait icons, generated by art/gen/trait_icons.py: edit that, never this file.", ""]
    for name, draw in TRAITS.items():
        lines += section(name, *draw())
    open(sys.argv[1], "w", encoding="utf-8").write("\n".join(lines))
    print(" ".join(TRAITS))
