"""Dig, combat skill and an animated reactor. Writes art/sprites/ui_actions2.toml"""
import math, sys
sys.path.insert(0, "."); sys.path.insert(0, sys.argv[1])
_a = sys.argv[:]; sys.argv = [sys.argv[0], sys.argv[1] + "/_ui_tmp.toml"]
from ui_icons import pickaxe  # noqa: E402
sys.argv = _a
from art.draw import Canvas, circ  # noqa: E402

c = Canvas()
out = ["# Dig, combat skill icon and the animated reactor. Generated by a script (art/draw.py); approved by the owner.\n"]

def emit(name, g, pal, frames=None):
    global out
    used = {ch for f in (frames or [(g, 0)]) for row in f[0] for ch in row if ch != "."}
    out.extend([f"[{name}]", 'kind = "free"', "outline = true",
                "palette = { " + ", ".join(f'{k} = "{v}"' for k, v in pal.items() if k in used) + " }"])
    if frames:
        out.append("")
        for fg, ms in frames:
            out += [f"[[{name}.frames]]", f"ms = {ms}", "rows = ["] + [f'  "{"".join(r)}",' for r in fg] + ["]", ""]
    else:
        out += ["rows = ["] + [f'  "{"".join(r)}",' for r in g] + ["]\n"]

def shift(g, dx, dy):
    out_ = [["." for _ in range(16)] for _ in range(16)]
    for y in range(16):
        for x in range(16):
            if g[y][x] != "." and 0 <= x + dx < 16 and 0 <= y + dy < 16:
                out_[y + dy][x + dx] = g[y][x]
    return out_


def spark(g, x, y, big):
    g = [row[:] for row in g]
    def put(px, py, ch):
        if 0 <= px < 16 and 0 <= py < 16:
            g[py][px] = ch
    put(x, y, "W")
    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        put(x + dx, y + dy, "Y")
    if big:
        for dx, dy in ((2, 0), (-2, 0), (0, 2), (0, -2)):
            put(x + dx, y + dy, "y")
    return g


# Dig (animated strike): wind up, swing, the point strikes and throws a spark at its bottom right, the spark fades.
c = Canvas()
pickaxe(c.g, 2, 14, 11, 5, 7, 9, 7.5, -105, 15, metal="Gg", wood="Bb")
base = c.g
dig_frames = [(shift(base, -1, -1), 240), (base, 70), (spark(base, 13, 12, True), 170), (spark(base, 13, 12, False), 130)]
emit("ui_dig", None, {"W": "#ffffff", "Y": "#ffe27a", "y": "#ffb030", "G": "#dfe8f4", "g": "#7e88a0", "B": "#c8905a",
                      "b": "#7a4c30"}, [(f, ms) for f, ms in dig_frames])

# Combat (animated clash): the swords pull apart, swing in, clash with a spark at the crossing, the spark fades.
def swords(apart):
    c = Canvas()
    def sword(m):
        X = (lambda x: x) if m == 1 else (lambda x: 15 - x)
        d = -apart if m == 1 else apart  # pull each sword outward
        for k in range(9):
            x, y = 5 + k, 10 - k
            c.put(X(x) + d, y + apart, "B")
            if k < 8:
                c.put(X(x) + d, y + 1 + apart, "b")
        for x, y in ((4, 9), (5, 10), (6, 11)):
            c.put(X(x) + d, y + apart, "Y")
        c.put(X(4) + d, 11 + apart, "h"); c.put(X(3) + d, 12 + apart, "h")
        c.put(X(2) + d, 13 + apart, "Y")
    sword(-1); sword(1)
    return c.g
together = swords(0)
clash_frames = [(swords(1), 240), (together, 70), (spark(together, 7, 5, True), 180), (spark(together, 7, 5, False), 130)]
emit("ui_skill_combat", None, {"B": "#f0f6ff", "b": "#8a96ac", "Y": "#ffd04a", "y": "#ffb030", "W": "#ffffff", "h": "#7a4c30"},
     clash_frames)

# Reactor (animated): a glass capsule between steel caps, its green core pulsing and two sparks orbiting it.
frames = []
for f, (r, ring) in enumerate(((1.6, "q"), (2.2, "Q"), (2.8, "Q"), (2.2, "q"))):
    c = Canvas()
    c.rect(3, 1, 12, 2, "S"); c.rect(3, 2, 12, 2, "s"); c.rect(5, 0, 10, 0, "s")  # top cap
    c.rect(3, 12, 12, 13, "S"); c.rect(3, 13, 12, 13, "s"); c.rect(2, 14, 13, 14, "s")  # base
    c.rect(4, 3, 11, 11, "k"); c.rect(4, 3, 4, 11, "G"); c.rect(11, 3, 11, 11, "g")  # glass
    c.fill(lambda x, y: 5 <= x <= 10 and 4 <= y <= 10 and math.hypot(x - 7.5, y - 7) <= r + 1.2, ring)  # glow
    c.fill(lambda x, y: math.hypot(x - 7.5, y - 7) <= r, "C")
    c.fill(lambda x, y: math.hypot(x - 7.2, y - 6.6) <= r * 0.45, "W")
    a = f * math.pi / 2
    for k in (0, math.pi):  # two orbiting sparks
        c.put(round(7.5 + 2.6 * math.cos(a + k)), round(7 + 3.2 * math.sin(a + k)), "W")
    for x in (5, 8, 10):
        c.put(x, 1, "L" if (x + f) % 2 else "s")  # blinking lights on the cap
    frames.append((c.g, 140))
emit("ui_reactor", None, {"S": "#b8c2d0", "s": "#6a7486", "k": "#14261e", "G": "#5a8a78", "g": "#2a4a40", "q": "#1e6a3a",
                          "Q": "#2e9a4a", "C": "#7aff8a", "W": "#f0fff0", "L": "#ffd04a"}, frames)
open("art/sprites/ui_actions2.toml", "w").write("\n".join(out))
