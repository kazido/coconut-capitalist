"""Smithing part icons: one drawing per part type (Base, Trim, Accent), tinted by tier with the shared TIERS ramps.

24 emoji: part_<type>_t<n>, n = 1..8 (docs/plans/tools-smithing.md, Art). Parts are items like any other, so each
sits in the rarity frame (art/rarity_style.py) of its rarity, and a part's tier IS its rarity (1 Common .. 8 Celestial). Every part uses the 4 letters P p q Q
(light -> dark) = TIERS[n], so a tier-3 part has exactly the colour a tier-3 head or handle has on a tool.
  base    an ingot block: the working end a tool is forged from
  trim    a wrapped grip: what you hold
  accent  a cut gem: the small finishing piece
Run: python art/gen/part_icons.py art/sprites/parts.toml
"""
import math
import sys

sys.path.insert(0, ".")
from art.draw import Canvas  # noqa: E402
from art.gen.tool_layers import TIERS, grab, poly  # noqa: E402



def drawings():
    c = Canvas()
    out = {}

    # Base: an ingot seen from the front-left. Top face lightest, front face mid, the right side in shadow.
    c.fill(poly([(2, 8), (10, 8), (10, 12), (2, 12)]), "p")
    c.fill(poly([(2, 8), (5, 5), (13, 5), (10, 8)]), "P")
    c.fill(poly([(10, 8), (13, 5), (13, 9), (10, 12)]), "Q")
    for x in range(3, 10):
        c.put(x, 11, "q")  # the bottom edge of the front face, in shade
    for x in range(6, 11):
        c.put(x, 6, "p")  # a cast groove along the top, so it reads as an ingot, not a box
    out["base"] = grab(c)

    # Trim: a 2px grip running bottom-left to top-right, wrapped in bands, with a darker cap at each end.
    r = math.sqrt(0.5)
    for y in range(16):
        for x in range(16):
            u = (x - 7.5 - (y - 7.5)) * r  # along the grip, toward the top-right
            w = (x - 7.5 + (y - 7.5)) * r  # across it, toward the bottom-right
            cap = abs(u) > 4.6
            if abs(u) > 6.2 or abs(w) > (2.0 if cap else 1.5):
                continue
            if cap:
                ch = "p" if w < -0.8 else ("q" if w < 0.6 else "Q")  # wider end caps (ferrules), lit on the top-left
            else:
                band = int(math.floor((u + 6) / 1.5)) % 2  # the wrap: light and dark turns
                lit = w < -0.4
                ch = ("P" if lit else "p") if band == 0 else ("p" if lit else "q")
                if w > 0.9:
                    ch = "Q"  # the shadowed underside
            c.put(x, y, ch)
    out["trim"] = grab(c)

    # Accent: a cut gem. Crown (top) lit, table pixel brightest, pavilion split light/dark down the middle.
    c.fill(poly([(3, 7), (6, 4), (10, 4), (13, 7)]), "p")
    c.fill(poly([(6, 4), (10, 4), (9, 6), (7, 6)]), "P")
    c.fill(poly([(3, 7), (13, 7), (8, 13)]), "q")
    c.fill(poly([(3, 7), (8, 7), (8, 13)]), "p")
    for x in range(4, 13):
        c.put(x, 7, "Q" if x > 8 else "q")  # the girdle line between crown and pavilion
    c.put(7, 5, "P")
    out["accent"] = grab(c)
    return out


def toml(sprites):
    lines = ["# Smithing part emoji, generated by art/gen/part_icons.py: edit that, never this file.", ""]
    for name, (g, ramp) in sprites.items():
        pal = dict(zip("PpqQ", ramp))
        used = {ch for row in g for ch in row if ch != "."}
        lines += [f"[{name}]", f"rarity = {name.rsplit('_t', 1)[1]}",
                  "palette = { " + ", ".join(f'{k} = "{v}"' for k, v in pal.items() if k in used) + " }",
                  "rows = ["] + [f'  "{"".join(r)}",' for r in g] + ["]", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    grids = drawings()
    sprites = {f"part_{kind}_t{n}": (grids[kind], TIERS[n]) for kind in grids for n in TIERS}
    open(sys.argv[1], "w", encoding="utf-8").write(toml(sprites))
    print(" ".join(sprites))
